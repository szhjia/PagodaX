export function normalizeLocale(value) { return value === 'zh-CN' ? value : 'en'; }
let locale = 'en';
try { if (typeof window !== 'undefined') locale = normalizeLocale(window.localStorage.getItem('pagodax.locale')); } catch { /* Storage may be blocked. */ }
export function getLocale() { return locale; }
export function setLocale(value) {
  locale = normalizeLocale(value);
  try { if (typeof window !== 'undefined') window.localStorage.setItem('pagodax.locale', locale); } catch { /* Switching still works without persistence. */ }
}
export function translate(language, key, values = {}) {
  const template = messages[normalizeLocale(language)][key] ?? messages.en[key];
  if (template === undefined) throw new Error('Unknown translation: ' + key);
  return template.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}
export const t = (key, values) => translate(locale, key, values);
export function applyTranslations(root = document) {
  document.documentElement.lang = locale;
  for (const attribute of ['text', 'aria-label', 'alt', 'title', 'content']) {
    const marker = attribute === 'text' ? 'data-i18n' : 'data-i18n-' + attribute;
    root.querySelectorAll('[' + marker + ']').forEach(element => {
      const value = t(element.getAttribute(marker));
      if (attribute === 'text') element.textContent = value;
      else element.setAttribute(attribute, value);
    });
  }
}
